import React, { useMemo } from "react";
import type { FeatureCollection } from "geojson";
import { StyleSheet, View } from "react-native";
import {
  Camera,
  FillLayer,
  Images,
  LineLayer,
  MapView,
  ShapeSource,
  SymbolLayer,
} from "@maplibre/maplibre-react-native";
import type { Waypoint } from "../domain/types";
import { color, mapColor } from "./theme";
import type { Ownship } from "./useOwnship";

import airspacesGeo from "../../assets/aero/airspaces.geojson";
import runwaysGeo from "../../assets/aero/runways.geojson";
import pointsGeo from "../../assets/aero/points_nav.geojson";

// OACI sprite set (generated by data/make_sprites.py). Registering them with
// the Images component guarantees iconImage names resolve — no missing-resource
// errors at runtime.
const SPRITES = {
  ownship: require("../../assets/sprites/ownship.png"),
  ad_paved: require("../../assets/sprites/ad_paved.png"),
  ad_unpaved: require("../../assets/sprites/ad_unpaved.png"),
  vor: require("../../assets/sprites/vor.png"),
  ndb: require("../../assets/sprites/ndb.png"),
  wpt: require("../../assets/sprites/wpt.png"),
};

export interface AeroMapProps {
  route: Waypoint[];
  ownship: Ownship | null;
  northUp: boolean;
  /** Absolute file URI of the local base_uruguay.pmtiles, or null. When null the
   * map draws the aeronautical layers over a neutral background, so they are
   * testable before the basemap is installed. */
  basemapUri?: string | null;
  /** file:// glyphs template (offline Noto Sans). Falls back to the demo font
   * server when null (online only). */
  glyphsUrl?: string | null;
}

const DEMO_GLYPHS = "https://demotiles.maplibre.org/font/{fontstack}/{range}.pbf";

// Base style built in code so the basemap source is only referenced when the
// PMTiles file is present; otherwise a clean neutral background (no broken
// tiles). Layer names follow the PROTOMAPS schema (earth/water/roads/places),
// not OpenMapTiles — the pmtiles from `make basemap` is a Protomaps build.
function baseStyle(basemapUri: string | null, glyphsUrl: string | null) {
  const glyphs = glyphsUrl ?? DEMO_GLYPHS;
  const bg = { id: "bg", type: "background", paint: { "background-color": color.bg } };
  if (!basemapUri) {
    return { version: 8, glyphs, sources: {}, layers: [bg] } as const;
  }
  return {
    version: 8,
    glyphs,
    sources: { basemap: { type: "vector", url: `pmtiles://${basemapUri}` } },
    layers: [
      bg,
      { id: "earth", type: "fill", source: "basemap", "source-layer": "earth",
        paint: { "fill-color": "#11181f" } },
      { id: "water", type: "fill", source: "basemap", "source-layer": "water",
        paint: { "fill-color": "#0e2233" } },
      { id: "landuse", type: "fill", source: "basemap", "source-layer": "landuse",
        paint: { "fill-color": "#13202b", "fill-opacity": 0.5 } },
      { id: "roads", type: "line", source: "basemap", "source-layer": "roads",
        paint: { "line-color": "#223042", "line-width": 0.6 } },
      { id: "places", type: "symbol", source: "basemap", "source-layer": "places",
        layout: { "text-field": ["get", "name"], "text-size": 11,
          "text-font": ["NotoSans"] },
        paint: { "text-color": "#5b6470", "text-halo-color": color.bg, "text-halo-width": 1 } },
    ],
  } as const;
}

function routeFeature(route: Waypoint[]): FeatureCollection {
  return {
    type: "FeatureCollection",
    features: route.length >= 2
      ? [{ type: "Feature", properties: {},
          geometry: { type: "LineString", coordinates: route.map((w) => [w.lon, w.lat]) } }]
      : [],
  } as FeatureCollection;
}

function ownshipFeature(o: Ownship | null): FeatureCollection {
  return {
    type: "FeatureCollection",
    features: o
      ? [{ type: "Feature",
          properties: { track: o.trackDeg ?? 0 },
          geometry: { type: "Point", coordinates: [o.lon, o.lat] } }]
      : [],
  } as FeatureCollection;
}

export function AeroMap({ route, ownship, northUp, basemapUri = null, glyphsUrl = null }: AeroMapProps) {
  const style = useMemo(() => baseStyle(basemapUri, glyphsUrl), [basemapUri, glyphsUrl]);
  const center: [number, number] = ownship
    ? [ownship.lon, ownship.lat]
    : route[0] ? [route[0].lon, route[0].lat] : [-56.03, -34.83]; // Carrasco
  const heading = !northUp && ownship?.trackDeg != null ? ownship.trackDeg : 0;

  return (
    <View style={styles.fill}>
      <MapView style={styles.fill} mapStyle={style as object} compassEnabled={northUp}>
        <Camera
          zoomLevel={9}
          centerCoordinate={center}
          heading={heading}
          animationMode="linearTo"
          animationDuration={500}
        />
        <Images images={SPRITES} />

        {/* Airspace: fill + outline + label */}
        <ShapeSource id="airspaces" shape={airspacesGeo as FeatureCollection}>
          <FillLayer id="as-fill" style={{ fillColor: mapColor.airspace, fillOpacity: 0.08 }} />
          <LineLayer id="as-line" style={{ lineColor: mapColor.airspace, lineWidth: 1.2, lineOpacity: 0.8 }} />
          <SymbolLayer id="as-label" style={{
            textField: ["get", "name"], textFont: ["NotoSans"], textSize: 11, symbolPlacement: "line",
            textColor: color.textMuted, textHaloColor: color.bg, textHaloWidth: 1,
          }} />
        </ShapeSource>

        {/* Runways */}
        <ShapeSource id="runways" shape={runwaysGeo as FeatureCollection}>
          <LineLayer id="rwy-line" style={{ lineColor: color.text, lineWidth: 2 }} />
        </ShapeSource>

        {/* Aerodromes / navaids / waypoints: OACI symbol by `sym` + label */}
        <ShapeSource id="points" shape={pointsGeo as FeatureCollection}>
          <SymbolLayer id="pt-sym" style={{
            iconImage: ["get", "sym"], iconSize: 0.9, iconAllowOverlap: true,
            textField: ["get", "ident"], textFont: ["NotoSans"], textSize: 11, textOffset: [0, 1.2], textAnchor: "top",
            textColor: color.text, textHaloColor: color.bg, textHaloWidth: 1,
            textOptional: true,
          }} />
        </ShapeSource>

        {/* Active route */}
        <ShapeSource id="route" shape={routeFeature(route)}>
          <LineLayer id="route-line" style={{ lineColor: mapColor.route, lineWidth: 3 }} />
        </ShapeSource>

        {/* Own-ship: aircraft icon rotated to the GPS track (map-aligned) */}
        <ShapeSource id="ownship" shape={ownshipFeature(ownship)}>
          <SymbolLayer id="ownship-icon" style={{
            iconImage: "ownship", iconRotate: ["get", "track"], iconRotationAlignment: "map",
            iconAllowOverlap: true, iconIgnorePlacement: true, iconSize: 1,
          }} />
        </ShapeSource>
      </MapView>
    </View>
  );
}

const styles = StyleSheet.create({ fill: { flex: 1 } });
